"""Generate docs/RESULTS.md and the README results block from the committed results/ files.

No number is typed by hand: every figure below is read from a JSON file written by a script.

    python -m tools.results_table
"""

import json
from typing import Any

from kws.envinfo import REPO_ROOT

RESULTS = REPO_ROOT / "results"
README = REPO_ROOT / "README.md"
BEGIN = "<!-- results:begin (generated by tools/results_table.py) -->"
END = "<!-- results:end -->"


def load(name: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads((RESULTS / name).read_text())
    return data


def latency_table() -> list[str]:
    rows = [
        "| Mode | Model | Threads | Features p50 / p95 (ms) | Inference p50 / p95 / p99 / max (ms) "
        "| Hop total p50 / p95 / p99 / max (ms) | Deadline misses (>20 ms) | Peak RSS (MB) "
        "| Python alloc / hop (bytes) |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for mode in ("baseline", "optimised"):
        for model in ("fp32", "int8"):
            for label, threads in (("1t", "1"), ("allt", "all")):
                f = RESULTS / f"latency_{mode}_{model}_{label}.json"
                if not f.exists():
                    continue
                d = load(f.name)
                a = d["aggregate"]

                def m(stage: str, p: str, a: dict[str, Any] = a) -> float:
                    return float(a[stage][p]["median"])

                alloc = d.get("allocations")
                alloc_s = f"{alloc['mean_bytes_per_hop']:,.0f}" if alloc else "n/a"
                rows.append(
                    f"| {mode} | {model.upper()} | {threads} "
                    f"| {m('features_ms', 'p50'):.3f} / {m('features_ms', 'p95'):.3f} "
                    f"| {m('inference_ms', 'p50'):.3f} / {m('inference_ms', 'p95'):.3f} / "
                    f"{m('inference_ms', 'p99'):.3f} / {m('inference_ms', 'max'):.2f} "
                    f"| {m('total_per_hop_ms', 'p50'):.3f} / {m('total_per_hop_ms', 'p95'):.3f} / "
                    f"{m('total_per_hop_ms', 'p99'):.3f} / {m('total_per_hop_ms', 'max'):.2f} "
                    f"| {a['deadline_misses']['median']:.0f} "
                    f"| {a['peak_rss_bytes']['median'] / 1e6:.0f} | {alloc_s} |"
                )
    return rows


def gc_table() -> list[str]:
    rows = [
        "| Model | GC | Hop total p95 (ms) | Hop total p99 (ms) | Hop total max (ms) |",
        "| --- | --- | --- | --- | --- |",
    ]
    for model in ("fp32", "int8"):
        for gc_label, name in (
            ("on", f"latency_optimised_{model}_1t.json"),
            ("off", f"latency_optimised_{model}_1t_nogc.json"),
        ):
            if not (RESULTS / name).exists():
                continue
            t = load(name)["aggregate"]["total_per_hop_ms"]
            rows.append(
                f"| {model.upper()} | {gc_label} | {t['p95']['median']:.3f} "
                f"| {t['p99']['median']:.3f} | {t['max']['median']:.2f} |"
            )
    return rows


def block() -> str:
    acc = load("accuracy.json")
    train = load("train_summary.json")
    test = load("stream_eval_test.json")
    val = load("stream_eval_val.json")
    parity = load("stream_feature_parity.json")
    op = test["operating_point"]
    lines = [
        "### Model (results/accuracy.json, results/train_summary.json)",
        "",
        "| | FP32 | INT8 |",
        "| --- | --- | --- |",
        f"| Test accuracy ({acc['test_clips']:,} clips, 12 classes) "
        f"| {acc['fp32_accuracy'] * 100:.2f} % | {acc['int8_accuracy'] * 100:.2f} % |",
    ]
    sizes = acc.get("model_size_bytes")
    if isinstance(sizes, dict):
        lines.append(f"| Model file size | {sizes['fp32_onnx']:,} B | {sizes['int8_onnx']:,} B |")
    params = train["parameter_count"]
    lines += [
        "",
        f"Parameters: {params:,}.",
        "",
        "### Streaming feature parity (results/stream_feature_parity.json)",
        "",
        f"Streaming MFCC vs batch reference: max |diff| "
        f"{parity['raw_mfcc_parity']['max_abs_diff']:.1e} over "
        f"{parity['raw_mfcc_parity']['clips']} clips; model inputs identical over "
        f"{parity['model_input_parity']['clips']:,} clips; predictions differing "
        f"FP32 {parity['prediction_parity']['fp32']['predictions_differing']}, "
        f"INT8 {parity['prediction_parity']['int8']['predictions_differing']}.",
        "",
        "### Stream detection (results/stream_eval_test.json)",
        "",
        f"Operating point chosen on the validation stream: threshold {op['threshold']}, "
        f"k = {op['smooth']}, 1 s suppression. Test stream: "
        f"{test['stream_seconds'] / 3600:.0f} hour.",
        "",
        "| Model | Keywords | Hits | Misses | Miss rate | False accepts | False accepts / hour |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for name in ("int8", "fp32"):
        r = test["models"][name]
        lines.append(
            f"| {name.upper()} | {r['keywords']} | {r['hits']} | {r['misses']} "
            f"| {r['miss_rate'] * 100:.1f} % | {r['false_accepts']} "
            f"| {r['false_accepts_per_hour']:.1f} |"
        )
    lines += [
        "",
        f"(Validation stream: {val['chosen']['miss_rate'] * 100:.1f} % miss, "
        f"{val['chosen']['false_accepts_per_hour']:.0f} false accepts/hour at the same point.)",
        "",
    ]
    if (RESULTS / "latency_optimised_int8_1t.json").exists():
        lines += [
            "### Latency (results/latency_*.json)",
            "",
            "Python on the host CPU, 1-hour test stream, median across repetitions of each "
            "percentile, 50 warm-up inferences excluded. Not device or accelerator latency.",
            "",
            *latency_table(),
            "",
        ]
        i8 = load("latency_optimised_int8_1t.json")["aggregate"]["inference_ms"]["p50"]["median"]
        f32 = load("latency_optimised_fp32_1t.json")["aggregate"]["inference_ms"]["p50"]["median"]
        ratio = i8 / f32
        lines += [
            f"INT8 / FP32 inference p50, optimised, 1 thread: {i8:.3f} ms / {f32:.3f} ms = "
            f"**{ratio:.2f}x** ({'slower' if ratio > 1 else 'faster'} for INT8).",
            "",
            "### Garbage collector (optimised, 1 thread)",
            "",
            *gc_table(),
            "",
        ]
    return "\n".join(lines)


def main() -> None:
    body = block()
    (REPO_ROOT / "docs" / "RESULTS.md").write_text(
        "# Results\n\nGenerated by `python -m tools.results_table` from `results/`. "
        "Do not edit by hand.\n\n" + body + "\n"
    )
    text = README.read_text()
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        README.write_text(head + BEGIN + "\n\n" + body + "\n" + END + tail)
    print("wrote docs/RESULTS.md and README results block")


if __name__ == "__main__":
    main()
